const Event = require('../models/Event');
const TicketType = require('../models/TicketType');
const Registration = require('../models/Registration');
const Payment = require('../models/Payment');
const AppError = require('../utils/AppError');

/**
 * Executes a ticket registration transaction with atomic oversell protection
 */
const createRegistrationWithPayment = async ({
  userId,
  eventId,
  ticketTypeId,
  quantity,
  paymentMethod,
}) => {
  // 1. Verify Event is published
  const event = await Event.findById(eventId);
  if (!event) {
    throw new AppError('The requested event does not exist.', 404);
  }

  if (event.status !== 'published') {
    throw new AppError(
      `Tickets can only be registered for published events. Current event status is '${event.status}'.`,
      400
    );
  }

  // 2. Check for duplicate registration by the same user for this ticket tier
  const existingReg = await Registration.findOne({
    user: userId,
    event: eventId,
    ticketType: ticketTypeId,
    status: 'confirmed',
  });
  if (existingReg) {
    throw new AppError(
      'You already have an active registration for this ticket tier. Please check My Tickets.',
      400
    );
  }

  // 3. Atomic conditional update on TicketType to prevent overselling
  const now = new Date();
  const ticket = await TicketType.findOneAndUpdate(
    {
      _id: ticketTypeId,
      event: eventId,
      saleStart: { $lte: now },
      saleEnd: { $gte: now },
      $expr: {
        $lte: [{ $add: ['$quantitySold', quantity] }, '$quantityTotal'],
      },
    },
    { $inc: { quantitySold: quantity } },
    { new: true }
  );

  if (!ticket) {
    // Determine precise reason for helpful user feedback
    const ticketCheck = await TicketType.findById(ticketTypeId);
    if (!ticketCheck) {
      throw new AppError('Ticket tier not found.', 404);
    }
    if (now < ticketCheck.saleStart) {
      throw new AppError(`Ticket sales for '${ticketCheck.name}' have not started yet.`, 400);
    }
    if (now > ticketCheck.saleEnd) {
      throw new AppError(`Ticket sales for '${ticketCheck.name}' have ended.`, 400);
    }
    const remaining = ticketCheck.quantityTotal - ticketCheck.quantitySold;
    throw new AppError(
      remaining <= 0
        ? `Ticket tier '${ticketCheck.name}' is completely sold out.`
        : `Only ${remaining} ticket(s) remaining for '${ticketCheck.name}'.`,
      400
    );
  }

  // 4. Create Registration record (registrationCode auto-generated by pre-validate hook)
  let registration;
  try {
    registration = await Registration.create({
      user: userId,
      event: eventId,
      ticketType: ticketTypeId,
      quantity,
      status: 'confirmed',
      attendance: 'pending',
    });
  } catch (err) {
    // If registration fails, rollback ticket quantity
    await TicketType.findByIdAndUpdate(ticketTypeId, {
      $inc: { quantitySold: -quantity },
    });
    throw err;
  }

  // 5. Create simulated Payment record
  const totalAmount = ticket.price * quantity;
  const payment = await Payment.create({
    registration: registration._id,
    amount: totalAmount,
    method: paymentMethod,
    status: 'paid',
    paidAt: new Date(),
  });

  // 6. Populate registration for rich response
  const populatedRegistration = await Registration.findById(registration._id)
    .populate('event', 'title startDate endDate venue category')
    .populate('ticketType', 'name price')
    .populate('user', 'name email');

  return {
    registration: populatedRegistration,
    payment,
  };
};

/**
 * Cancels a confirmed registration and atomically restores inventory
 */
const cancelRegistration = async (registrationId, requestingUser) => {
  const registration = await Registration.findById(registrationId).populate('event');
  if (!registration) {
    throw new AppError('Registration not found.', 404);
  }

  // Permission check: owner attendee, event organizer, or admin
  const isOwner = registration.user.toString() === requestingUser._id.toString();
  const isOrganizer =
    requestingUser.role === 'organizer' &&
    registration.event.organizer.toString() === requestingUser._id.toString();
  const isAdmin = requestingUser.role === 'admin';

  if (!isOwner && !isOrganizer && !isAdmin) {
    throw new AppError('You are not authorized to cancel this registration.', 403);
  }

  if (registration.status === 'cancelled') {
    throw new AppError('This registration has already been cancelled.', 400);
  }

  // Atomically restore quantitySold on TicketType
  await TicketType.findByIdAndUpdate(registration.ticketType, {
    $inc: { quantitySold: -registration.quantity },
  });

  // Mark registration as cancelled
  registration.status = 'cancelled';
  await registration.save();

  // Mark matching payment as refunded
  await Payment.findOneAndUpdate(
    { registration: registration._id },
    { status: 'refunded' }
  );

  return registration;
};

/**
 * Fast attendance check-in by registration code or ID
 */
const checkInRegistration = async (registrationId, attendanceStatus, requestingUser) => {
  const registration = await Registration.findById(registrationId).populate('event');
  if (!registration) {
    throw new AppError('Registration not found.', 404);
  }

  // Check that requesting user is organizer of this event or admin
  const isOrganizer =
    requestingUser.role === 'organizer' &&
    registration.event.organizer.toString() === requestingUser._id.toString();
  const isAdmin = requestingUser.role === 'admin';

  if (!isOrganizer && !isAdmin) {
    throw new AppError('Only the event organizer or an admin can manage attendance check-in.', 403);
  }

  if (registration.status === 'cancelled') {
    throw new AppError('Cannot check in a cancelled registration.', 400);
  }

  registration.attendance = attendanceStatus;
  registration.checkedInAt = attendanceStatus === 'checked_in' ? new Date() : null;
  await registration.save();

  return registration;
};

module.exports = {
  createRegistrationWithPayment,
  cancelRegistration,
  checkInRegistration,
};
